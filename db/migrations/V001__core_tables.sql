   - Kolom audit: CREATED_BY/CREATED_DT/UPDATED_BY/UPDATED_DT, ROW_VER untuk optimistic concurrency.
   - Waktu disimpan sebagai waktu server (WIB, UTC+7).
   ============================================================================= */

    OFFICE_NM    nvarchar(100)  NOT NULL,
    CITY         nvarchar(50)   NOT NULL,
    ADDRESS      nvarchar(250)  NULL,
    PIC_USER_ID  varchar(20)    NULL,          -- FK ke TB_M_USER ditambahkan di bawah (relasi melingkar)

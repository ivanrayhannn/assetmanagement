/* =============================================================================
   V001 - Tabel inti AMS (FSD §5 Data Model)
   Master   : TB_M_OFFICE, TB_M_CATEGORY, TB_M_USER, TB_M_ASSET, TB_M_ASSET_SEQ
   Transaksi: TB_T_ASSET_HISTORY, TB_T_ASSIGNMENT, TB_T_OPNAME_H, TB_T_OPNAME_D
   Pendukung: TB_T_EMAIL_OUTBOX, TB_T_AUDIT_LOG

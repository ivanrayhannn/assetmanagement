    UPDATED_BY   varchar(20)    NULL,
    UPDATED_DT   datetime2(0)   NULL,
    CONSTRAINT PK_TB_M_OFFICE PRIMARY KEY (OFFICE_CD),
    CONSTRAINT CK_TB_M_OFFICE_CD CHECK (OFFICE_CD LIKE '[A-Z][A-Z][A-Z]')
);

CREATE TABLE dbo.TB_M_CATEGORY (
    CATEGORY_CD  varchar(3)     NOT NULL,
    CATEGORY_NM  nvarchar(50)   NOT NULL,
    IS_ACTIVE    bit            NOT NULL CONSTRAINT DF_TB_M_CATEGORY_ACTIVE DEFAULT (1),
    CREATED_BY   varchar(20)    NOT NULL,
    CREATED_DT   datetime2(0)   NOT NULL CONSTRAINT DF_TB_M_CATEGORY_CDT DEFAULT (SYSDATETIME()),
    UPDATED_BY   varchar(20)    NULL,
    UPDATED_DT   datetime2(0)   NULL,
    CONSTRAINT PK_TB_M_CATEGORY PRIMARY KEY (CATEGORY_CD),
    CONSTRAINT CK_TB_M_CATEGORY_CD CHECK (CATEGORY_CD LIKE '[A-Z][A-Z][A-Z]')
);

/* ROLE_CD: ADMIN_GA | PIC | USER | EXEC. Di produksi diturunkan dari AD group
   (AMS_ADMIN_GA, AMS_PIC_<KANTOR>, AMS_EXEC, default USER) dan disinkron ke kolom ini. */
CREATE TABLE dbo.TB_M_USER (
    USER_ID      varchar(20)    NOT NULL,      -- NIK / sAMAccountName
    USER_NM      nvarchar(100)  NOT NULL,
    EMAIL        varchar(100)   NULL,
    AD_ACCOUNT   varchar(100)   NULL,          -- DOMAIN\username atau UPN, untuk mapping SSO
    DEPT         nvarchar(50)   NULL,
    OFFICE_CD    varchar(3)     NOT NULL,
    ROLE_CD      varchar(10)    NOT NULL CONSTRAINT DF_TB_M_USER_ROLE DEFAULT ('USER'),
    IS_ACTIVE    bit            NOT NULL CONSTRAINT DF_TB_M_USER_ACTIVE DEFAULT (1),
    RESIGN_DT    date           NULL,          -- diisi oleh sync HR
    CREATED_BY   varchar(20)    NOT NULL,
    CREATED_DT   datetime2(0)   NOT NULL CONSTRAINT DF_TB_M_USER_CDT DEFAULT (SYSDATETIME()),
    UPDATED_BY   varchar(20)    NULL,
    UPDATED_DT   datetime2(0)   NULL,
    CONSTRAINT PK_TB_M_USER PRIMARY KEY (USER_ID),
    CONSTRAINT FK_TB_M_USER_OFFICE FOREIGN KEY (OFFICE_CD) REFERENCES dbo.TB_M_OFFICE (OFFICE_CD),
    CONSTRAINT CK_TB_M_USER_ROLE CHECK (ROLE_CD IN ('ADMIN_GA', 'PIC', 'USER', 'EXEC'))
);

ALTER TABLE dbo.TB_M_OFFICE
    ADD CONSTRAINT FK_TB_M_OFFICE_PIC FOREIGN KEY (PIC_USER_ID) REFERENCES dbo.TB_M_USER (USER_ID);

/* Pusat data model. Status: AVAILABLE | IN_USE | UNDER_REPAIR | MISSING | DISPOSED
   BR-01: ASSET_NO unik & immutable (trigger di V003), format AST-[KANTOR]-[KATEGORI]-[TAHUN]-[SEQ4].
   BR-02: satu asset satu user (kolom USER_ID tunggal); IN_USE wajib punya user,
          AVAILABLE/MISSING/DISPOSED tidak dipegang user. */
CREATE TABLE dbo.TB_M_ASSET (
    ASSET_NO     varchar(21)    NOT NULL,
    ASSET_NM     nvarchar(150)  NOT NULL,
    CATEGORY_CD  varchar(3)     NOT NULL,
    BRAND_MODEL  nvarchar(100)  NULL,
    SERIAL_NO    varchar(100)   NULL,
    ACQ_DT       date           NOT NULL,
    OFFICE_CD    varchar(3)     NOT NULL,
    USER_ID      varchar(20)    NULL,
    STATUS       varchar(15)    NOT NULL CONSTRAINT DF_TB_M_ASSET_STATUS DEFAULT ('AVAILABLE'),
    CONDITION    varchar(15)    NOT NULL CONSTRAINT DF_TB_M_ASSET_COND DEFAULT ('BAIK'),
    REMARK       nvarchar(500)  NULL,
    CREATED_BY   varchar(20)    NOT NULL,
    CREATED_DT   datetime2(0)   NOT NULL CONSTRAINT DF_TB_M_ASSET_CDT DEFAULT (SYSDATETIME()),
    UPDATED_BY   varchar(20)    NULL,
    UPDATED_DT   datetime2(0)   NULL,
    ROW_VER      rowversion     NOT NULL,
    CONSTRAINT PK_TB_M_ASSET PRIMARY KEY (ASSET_NO),
    CONSTRAINT FK_TB_M_ASSET_CATEGORY FOREIGN KEY (CATEGORY_CD) REFERENCES dbo.TB_M_CATEGORY (CATEGORY_CD),
    CONSTRAINT FK_TB_M_ASSET_OFFICE   FOREIGN KEY (OFFICE_CD)   REFERENCES dbo.TB_M_OFFICE (OFFICE_CD),
    CONSTRAINT FK_TB_M_ASSET_USER     FOREIGN KEY (USER_ID)     REFERENCES dbo.TB_M_USER (USER_ID),
    CONSTRAINT CK_TB_M_ASSET_NO_FORMAT CHECK (
        ASSET_NO LIKE 'AST-[A-Z][A-Z][A-Z]-[A-Z][A-Z][A-Z]-[12][0-9][0-9][0-9]-[0-9][0-9][0-9][0-9]'
        AND SUBSTRING(ASSET_NO, 9, 3) = CATEGORY_CD),           -- kategori di nomor tidak boleh berubah
    CONSTRAINT CK_TB_M_ASSET_STATUS CHECK (STATUS IN ('AVAILABLE', 'IN_USE', 'UNDER_REPAIR', 'MISSING', 'DISPOSED')),
    CONSTRAINT CK_TB_M_ASSET_CONDITION CHECK (CONDITION IN ('BAIK', 'RUSAK_RINGAN', 'RUSAK_BERAT')),
    CONSTRAINT CK_TB_M_ASSET_STATUS_USER CHECK (
        (STATUS = 'IN_USE' AND USER_ID IS NOT NULL)
        OR (STATUS IN ('AVAILABLE', 'MISSING', 'DISPOSED') AND USER_ID IS NULL)
        OR STATUS = 'UNDER_REPAIR')
);

/* BR-01: sequence nomor asset di-reset per kantor-kategori-tahun.
   Diambil lewat dbo.USP_ASSET_NEXT_NO (V003) dengan lock agar tidak ada nomor ganda. */
CREATE TABLE dbo.TB_M_ASSET_SEQ (
    OFFICE_CD    varchar(3)     NOT NULL,
    CATEGORY_CD  varchar(3)     NOT NULL,
    SEQ_YEAR     smallint       NOT NULL,
    LAST_SEQ     int            NOT NULL,
    UPDATED_DT   datetime2(0)   NOT NULL CONSTRAINT DF_TB_M_ASSET_SEQ_UDT DEFAULT (SYSDATETIME()),
    CONSTRAINT PK_TB_M_ASSET_SEQ PRIMARY KEY (OFFICE_CD, CATEGORY_CD, SEQ_YEAR),
    CONSTRAINT FK_TB_M_ASSET_SEQ_OFFICE   FOREIGN KEY (OFFICE_CD)   REFERENCES dbo.TB_M_OFFICE (OFFICE_CD),
    CONSTRAINT FK_TB_M_ASSET_SEQ_CATEGORY FOREIGN KEY (CATEGORY_CD) REFERENCES dbo.TB_M_CATEGORY (CATEGORY_CD),
    CONSTRAINT CK_TB_M_ASSET_SEQ_RANGE CHECK (LAST_SEQ BETWEEN 0 AND 9999)
);

/* ----------------------------------------------------------- Transaksi ---- */

/* Sesi stock opname. STATUS: OPEN | SUBMITTED | APPROVED
   BR-05: QTY_FOUND = QTY_SYSTEM - QTY_MINUS.
   SoD (SA §6): approver tidak boleh sama dengan yang submit. */
CREATE TABLE dbo.TB_T_OPNAME_H (
    OPNAME_ID     int            NOT NULL IDENTITY(1, 1),
    OFFICE_CD     varchar(3)     NOT NULL,
    PERIOD        char(7)        NOT NULL,       -- YYYY-MM
    STATUS        varchar(10)    NOT NULL CONSTRAINT DF_TB_T_OPNAME_H_STATUS DEFAULT ('OPEN'),
    QTY_SYSTEM    int            NOT NULL CONSTRAINT DF_TB_T_OPNAME_H_SYS   DEFAULT (0),
    QTY_FOUND     int            NOT NULL CONSTRAINT DF_TB_T_OPNAME_H_FOUND DEFAULT (0),
    QTY_MINUS     int            NOT NULL CONSTRAINT DF_TB_T_OPNAME_H_MINUS DEFAULT (0),
    QTY_PLUS      int            NOT NULL CONSTRAINT DF_TB_T_OPNAME_H_PLUS  DEFAULT (0),
    REMARK        nvarchar(500)  NULL,
    CREATED_BY    varchar(20)    NOT NULL,
    CREATED_DT    datetime2(0)   NOT NULL CONSTRAINT DF_TB_T_OPNAME_H_CDT DEFAULT (SYSDATETIME()),
    SUBMITTED_BY  varchar(20)    NULL,
    SUBMITTED_DT  datetime2(0)   NULL,
    APPROVED_BY   varchar(20)    NULL,
    APPROVED_DT   datetime2(0)   NULL,
    ROW_VER       rowversion     NOT NULL,
    CONSTRAINT PK_TB_T_OPNAME_H PRIMARY KEY (OPNAME_ID),
    CONSTRAINT FK_TB_T_OPNAME_H_OFFICE    FOREIGN KEY (OFFICE_CD)    REFERENCES dbo.TB_M_OFFICE (OFFICE_CD),
    CONSTRAINT FK_TB_T_OPNAME_H_CREATED   FOREIGN KEY (CREATED_BY)   REFERENCES dbo.TB_M_USER (USER_ID),
    CONSTRAINT FK_TB_T_OPNAME_H_SUBMITTED FOREIGN KEY (SUBMITTED_BY) REFERENCES dbo.TB_M_USER (USER_ID),
    CONSTRAINT FK_TB_T_OPNAME_H_APPROVED  FOREIGN KEY (APPROVED_BY)  REFERENCES dbo.TB_M_USER (USER_ID),
    CONSTRAINT UQ_TB_T_OPNAME_H_PERIOD UNIQUE (OFFICE_CD, PERIOD),
    CONSTRAINT CK_TB_T_OPNAME_H_PERIOD CHECK (PERIOD LIKE '[12][0-9][0-9][0-9]-[01][0-9]' AND RIGHT(PERIOD, 2) BETWEEN '01' AND '12'),
    CONSTRAINT CK_TB_T_OPNAME_H_STATUS CHECK (STATUS IN ('OPEN', 'SUBMITTED', 'APPROVED')),
    CONSTRAINT CK_TB_T_OPNAME_H_QTY CHECK (
        QTY_SYSTEM >= 0 AND QTY_MINUS >= 0 AND QTY_PLUS >= 0
        AND QTY_MINUS <= QTY_SYSTEM AND QTY_FOUND = QTY_SYSTEM - QTY_MINUS),
    CONSTRAINT CK_TB_T_OPNAME_H_FLOW CHECK (
        (STATUS = 'OPEN'      AND SUBMITTED_DT IS NULL     AND APPROVED_DT IS NULL)
     OR (STATUS = 'SUBMITTED' AND SUBMITTED_DT IS NOT NULL AND APPROVED_DT IS NULL)
     OR (STATUS = 'APPROVED'  AND SUBMITTED_DT IS NOT NULL AND APPROVED_DT IS NOT NULL)),
    CONSTRAINT CK_TB_T_OPNAME_H_SOD CHECK (APPROVED_BY IS NULL OR SUBMITTED_BY IS NULL OR APPROVED_BY <> SUBMITTED_BY)
);

/* Detail opname: snapshot asset (SYS_*) saat sesi dibuat + hasil cek PIC.
   RESULT: SESUAI | BEDA_LOKASI | RUSAK | TIDAK_DITEMUKAN | PLUS (NULL = belum dicek, BR-06).
   Temuan PLUS tidak punya ASSET_NO, sehingga PK memakai surrogate OPNAME_D_ID;
   keunikan (OPNAME_ID, ASSET_NO) dijaga unique index terfilter di V002. */
CREATE TABLE dbo.TB_T_OPNAME_D (
    OPNAME_D_ID      bigint         NOT NULL IDENTITY(1, 1),
    OPNAME_ID        int            NOT NULL,
    ASSET_NO         varchar(21)    NULL,
    SYS_CATEGORY_CD  varchar(3)     NOT NULL,     -- untuk temuan PLUS: kategori perkiraan PIC
    SYS_USER_ID      varchar(20)    NULL,
    SYS_OFFICE       varchar(3)     NULL,
    SYS_STATUS       varchar(15)    NULL,
    RESULT           varchar(15)    NULL,
    ACTUAL_USER_ID   varchar(20)    NULL,
    ACTUAL_OFFICE    varchar(3)     NULL,
    PLUS_DESC        nvarchar(200)  NULL,
    PLUS_SERIAL_NO   varchar(100)   NULL,
    REMARK           nvarchar(500)  NULL,
    CHECKED_BY       varchar(20)    NULL,
    CHECKED_DT       datetime2(0)   NULL,
    ROW_VER          rowversion     NOT NULL,
    CONSTRAINT PK_TB_T_OPNAME_D PRIMARY KEY (OPNAME_D_ID),
    CONSTRAINT FK_TB_T_OPNAME_D_H        FOREIGN KEY (OPNAME_ID)       REFERENCES dbo.TB_T_OPNAME_H (OPNAME_ID),
    CONSTRAINT FK_TB_T_OPNAME_D_ASSET    FOREIGN KEY (ASSET_NO)        REFERENCES dbo.TB_M_ASSET (ASSET_NO),
    CONSTRAINT FK_TB_T_OPNAME_D_CATEGORY FOREIGN KEY (SYS_CATEGORY_CD) REFERENCES dbo.TB_M_CATEGORY (CATEGORY_CD),
    CONSTRAINT FK_TB_T_OPNAME_D_SYSUSER  FOREIGN KEY (SYS_USER_ID)     REFERENCES dbo.TB_M_USER (USER_ID),
    CONSTRAINT FK_TB_T_OPNAME_D_ACTUSER  FOREIGN KEY (ACTUAL_USER_ID)  REFERENCES dbo.TB_M_USER (USER_ID),
    CONSTRAINT FK_TB_T_OPNAME_D_ACTOFF   FOREIGN KEY (ACTUAL_OFFICE)   REFERENCES dbo.TB_M_OFFICE (OFFICE_CD),
    CONSTRAINT FK_TB_T_OPNAME_D_CHECKED  FOREIGN KEY (CHECKED_BY)      REFERENCES dbo.TB_M_USER (USER_ID),
    CONSTRAINT CK_TB_T_OPNAME_D_RESULT CHECK (RESULT IN ('SESUAI', 'BEDA_LOKASI', 'RUSAK', 'TIDAK_DITEMUKAN', 'PLUS')),
    CONSTRAINT CK_TB_T_OPNAME_D_PLUS CHECK (
        (RESULT = 'PLUS' AND ASSET_NO IS NULL AND PLUS_DESC IS NOT NULL)
     OR (ISNULL(RESULT, '') <> 'PLUS' AND ASSET_NO IS NOT NULL AND SYS_OFFICE IS NOT NULL AND SYS_STATUS IS NOT NULL)),
    CONSTRAINT CK_TB_T_OPNAME_D_BEDA CHECK (
        RESULT <> 'BEDA_LOKASI' OR ACTUAL_USER_ID IS NOT NULL OR ACTUAL_OFFICE IS NOT NULL),
    CONSTRAINT CK_TB_T_OPNAME_D_CHECKED CHECK (
        (RESULT IS NULL AND CHECKED_DT IS NULL) OR (RESULT IS NOT NULL AND CHECKED_DT IS NOT NULL AND CHECKED_BY IS NOT NULL))
);

/* Riwayat pemakai/lokasi/status (append-only, dijaga trigger di V003).
   ACTION: REGISTER | ASSIGN | TRANSFER | RETURN | STATUS_CHANGE */
CREATE TABLE dbo.TB_T_ASSET_HISTORY (
    HIST_ID      bigint         NOT NULL IDENTITY(1, 1),
    ASSET_NO     varchar(21)    NOT NULL,
    ACTION       varchar(15)    NOT NULL,
    FROM_USER    varchar(20)    NULL,
    TO_USER      varchar(20)    NULL,
    FROM_OFFICE  varchar(3)     NULL,
    TO_OFFICE    varchar(3)     NULL,
    FROM_STATUS  varchar(15)    NULL,
    TO_STATUS    varchar(15)    NULL,
    REASON       nvarchar(500)  NULL,
    OPNAME_ID    int            NULL,          -- terisi bila perubahan berasal dari approve opname (BR-07)
    CREATED_BY   varchar(20)    NOT NULL,
    CREATED_DT   datetime2(0)   NOT NULL CONSTRAINT DF_TB_T_ASSET_HISTORY_CDT DEFAULT (SYSDATETIME()),
    CONSTRAINT PK_TB_T_ASSET_HISTORY PRIMARY KEY (HIST_ID),
    CONSTRAINT FK_TB_T_ASSET_HISTORY_ASSET  FOREIGN KEY (ASSET_NO)    REFERENCES dbo.TB_M_ASSET (ASSET_NO),
    CONSTRAINT FK_TB_T_ASSET_HISTORY_FUSER  FOREIGN KEY (FROM_USER)   REFERENCES dbo.TB_M_USER (USER_ID),
    CONSTRAINT FK_TB_T_ASSET_HISTORY_TUSER  FOREIGN KEY (TO_USER)     REFERENCES dbo.TB_M_USER (USER_ID),
    CONSTRAINT FK_TB_T_ASSET_HISTORY_FOFF   FOREIGN KEY (FROM_OFFICE) REFERENCES dbo.TB_M_OFFICE (OFFICE_CD),
    CONSTRAINT FK_TB_T_ASSET_HISTORY_TOFF   FOREIGN KEY (TO_OFFICE)   REFERENCES dbo.TB_M_OFFICE (OFFICE_CD),
    CONSTRAINT FK_TB_T_ASSET_HISTORY_OPNAME FOREIGN KEY (OPNAME_ID)   REFERENCES dbo.TB_T_OPNAME_H (OPNAME_ID),
    CONSTRAINT CK_TB_T_ASSET_HISTORY_ACTION CHECK (ACTION IN ('REGISTER', 'ASSIGN', 'TRANSFER', 'RETURN', 'STATUS_CHANGE'))
);

/* Permintaan assign / mutasi ke user yang menunggu konfirmasi terima (UC-01).
   Selama PENDING asset tetap AVAILABLE (assign) atau tetap di user lama (mutasi);
   saat CONFIRMED API meng-update TB_M_ASSET + menulis TB_T_ASSET_HISTORY.
   ASSIGN_TYPE: ASSIGN | TRANSFER. STATUS: PENDING | CONFIRMED | REJECTED | CANCELLED */
CREATE TABLE dbo.TB_T_ASSIGNMENT (
    ASSIGNMENT_ID  bigint         NOT NULL IDENTITY(1, 1),
    ASSET_NO       varchar(21)    NOT NULL,
    ASSIGN_TYPE    varchar(10)    NOT NULL,
    FROM_USER      varchar(20)    NULL,
    TO_USER        varchar(20)    NOT NULL,
    FROM_OFFICE    varchar(3)     NOT NULL,
    TO_OFFICE      varchar(3)     NOT NULL,
    REASON         nvarchar(500)  NULL,
    STATUS         varchar(10)    NOT NULL CONSTRAINT DF_TB_T_ASSIGNMENT_STATUS DEFAULT ('PENDING'),
    RESPONSE_NOTE  nvarchar(500)  NULL,       -- alasan tolak dari user
    REQUESTED_BY   varchar(20)    NOT NULL,
    REQUESTED_DT   datetime2(0)   NOT NULL CONSTRAINT DF_TB_T_ASSIGNMENT_RDT DEFAULT (SYSDATETIME()),
    RESPONDED_DT   datetime2(0)   NULL,
    ROW_VER        rowversion     NOT NULL,
    CONSTRAINT PK_TB_T_ASSIGNMENT PRIMARY KEY (ASSIGNMENT_ID),
    CONSTRAINT FK_TB_T_ASSIGNMENT_ASSET FOREIGN KEY (ASSET_NO)     REFERENCES dbo.TB_M_ASSET (ASSET_NO),
    CONSTRAINT FK_TB_T_ASSIGNMENT_FUSER FOREIGN KEY (FROM_USER)    REFERENCES dbo.TB_M_USER (USER_ID),
    CONSTRAINT FK_TB_T_ASSIGNMENT_TUSER FOREIGN KEY (TO_USER)      REFERENCES dbo.TB_M_USER (USER_ID),
    CONSTRAINT FK_TB_T_ASSIGNMENT_FOFF  FOREIGN KEY (FROM_OFFICE)  REFERENCES dbo.TB_M_OFFICE (OFFICE_CD),
    CONSTRAINT FK_TB_T_ASSIGNMENT_TOFF  FOREIGN KEY (TO_OFFICE)    REFERENCES dbo.TB_M_OFFICE (OFFICE_CD),
    CONSTRAINT FK_TB_T_ASSIGNMENT_REQ   FOREIGN KEY (REQUESTED_BY) REFERENCES dbo.TB_M_USER (USER_ID),
    CONSTRAINT CK_TB_T_ASSIGNMENT_TYPE CHECK (ASSIGN_TYPE IN ('ASSIGN', 'TRANSFER')),
    CONSTRAINT CK_TB_T_ASSIGNMENT_STATUS CHECK (STATUS IN ('PENDING', 'CONFIRMED', 'REJECTED', 'CANCELLED')),
    CONSTRAINT CK_TB_T_ASSIGNMENT_REJECT CHECK (STATUS <> 'REJECTED' OR RESPONSE_NOTE IS NOT NULL),
    CONSTRAINT CK_TB_T_ASSIGNMENT_RESP CHECK ((STATUS = 'PENDING' AND RESPONDED_DT IS NULL) OR (STATUS <> 'PENDING' AND RESPONDED_DT IS NOT NULL))
);

/* ----------------------------------------------------------- Pendukung ---- */

/* Outbox notifikasi email (SA §5): ditulis dalam transaksi bisnis, dikirim Hangfire dengan retry. */
CREATE TABLE dbo.TB_T_EMAIL_OUTBOX (
    OUTBOX_ID    bigint          NOT NULL IDENTITY(1, 1),
    EVENT_TYPE   varchar(30)     NOT NULL,     -- ASSIGN_REQUEST, OPNAME_OPENED, OPNAME_SUBMITTED, OPNAME_APPROVED, ...
    REF_ID       varchar(50)     NULL,
    TO_ADDR      varchar(500)    NOT NULL,
    SUBJECT      nvarchar(200)   NOT NULL,
    BODY         nvarchar(max)   NOT NULL,
    STATUS       varchar(10)     NOT NULL CONSTRAINT DF_TB_T_EMAIL_OUTBOX_STATUS DEFAULT ('PENDING'),
    RETRY_COUNT  tinyint         NOT NULL CONSTRAINT DF_TB_T_EMAIL_OUTBOX_RETRY DEFAULT (0),
    LAST_ERROR   nvarchar(1000)  NULL,
    CREATED_DT   datetime2(0)    NOT NULL CONSTRAINT DF_TB_T_EMAIL_OUTBOX_CDT DEFAULT (SYSDATETIME()),
    SENT_DT      datetime2(0)    NULL,
    CONSTRAINT PK_TB_T_EMAIL_OUTBOX PRIMARY KEY (OUTBOX_ID),
    CONSTRAINT CK_TB_T_EMAIL_OUTBOX_STATUS CHECK (STATUS IN ('PENDING', 'SENT', 'FAILED'))
);

/* Audit trail aksi user (SA §6): siapa, kapan, dari IP mana, mengubah apa. */
CREATE TABLE dbo.TB_T_AUDIT_LOG (
    AUDIT_ID     bigint          NOT NULL IDENTITY(1, 1),
    USER_ID      varchar(20)     NOT NULL,
    ACTION       varchar(50)     NOT NULL,     -- ASSET_CREATE, ASSET_UPDATE, OPNAME_APPROVE, ...
    ENTITY       varchar(50)     NOT NULL,
    ENTITY_ID    varchar(50)     NOT NULL,
    DETAIL       nvarchar(max)   NULL,         -- JSON before/after
    IP_ADDR      varchar(45)     NULL,
    CREATED_DT   datetime2(0)    NOT NULL CONSTRAINT DF_TB_T_AUDIT_LOG_CDT DEFAULT (SYSDATETIME()),
    CONSTRAINT PK_TB_T_AUDIT_LOG PRIMARY KEY (AUDIT_ID),
    CONSTRAINT CK_TB_T_AUDIT_LOG_DETAIL CHECK (DETAIL IS NULL OR ISJSON(DETAIL) = 1)
);

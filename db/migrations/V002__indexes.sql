/* TB_M_USER */
CREATE INDEX IX_TB_M_USER_OFFICE ON dbo.TB_M_USER (OFFICE_CD, IS_ACTIVE) INCLUDE (USER_NM, ROLE_CD);
CREATE UNIQUE INDEX UX_TB_M_USER_AD_ACCOUNT ON dbo.TB_M_USER (AD_ACCOUNT) WHERE AD_ACCOUNT IS NOT NULL;

/* TB_M_ASSET: list & filter (FR-05), dashboard KPI, scope User */
CREATE INDEX IX_TB_M_ASSET_OFFICE_STATUS ON dbo.TB_M_ASSET (OFFICE_CD, STATUS) INCLUDE (CATEGORY_CD, USER_ID, ASSET_NM);
CREATE INDEX IX_TB_M_ASSET_USER          ON dbo.TB_M_ASSET (USER_ID) WHERE USER_ID IS NOT NULL;
CREATE INDEX IX_TB_M_ASSET_CATEGORY      ON dbo.TB_M_ASSET (CATEGORY_CD, STATUS);
/* Cegah registrasi ganda perangkat yang sama */
CREATE UNIQUE INDEX UX_TB_M_ASSET_SERIAL ON dbo.TB_M_ASSET (CATEGORY_CD, SERIAL_NO) WHERE SERIAL_NO IS NOT NULL;

/* TB_T_ASSET_HISTORY: timeline per asset (SCR-04) */
CREATE INDEX IX_TB_T_ASSET_HISTORY_ASSET ON dbo.TB_T_ASSET_HISTORY (ASSET_NO, CREATED_DT DESC);
CREATE INDEX IX_TB_T_ASSET_HISTORY_USER  ON dbo.TB_T_ASSET_HISTORY (TO_USER) WHERE TO_USER IS NOT NULL;

/* TB_T_ASSIGNMENT: BR-02, satu permintaan PENDING per asset */
CREATE UNIQUE INDEX UX_TB_T_ASSIGNMENT_PENDING ON dbo.TB_T_ASSIGNMENT (ASSET_NO) WHERE STATUS = 'PENDING';
CREATE INDEX IX_TB_T_ASSIGNMENT_TO_USER ON dbo.TB_T_ASSIGNMENT (TO_USER, STATUS);

/* TB_T_OPNAME_H: maksimal satu sesi aktif (OPEN/SUBMITTED) per kantor -> dasar freeze BR-04 */
CREATE UNIQUE INDEX UX_TB_T_OPNAME_H_ACTIVE ON dbo.TB_T_OPNAME_H (OFFICE_CD) WHERE STATUS IN ('OPEN', 'SUBMITTED');
CREATE INDEX IX_TB_T_OPNAME_H_PERIOD ON dbo.TB_T_OPNAME_H (PERIOD, STATUS) INCLUDE (OFFICE_CD, QTY_SYSTEM, QTY_FOUND, QTY_MINUS, QTY_PLUS);

/* TB_T_OPNAME_D: satu baris per asset per sesi; hitung selisih per hasil (BR-05, BR-06) */
CREATE UNIQUE INDEX UX_TB_T_OPNAME_D_ASSET ON dbo.TB_T_OPNAME_D (OPNAME_ID, ASSET_NO) WHERE ASSET_NO IS NOT NULL;
CREATE INDEX IX_TB_T_OPNAME_D_RESULT ON dbo.TB_T_OPNAME_D (OPNAME_ID, RESULT) INCLUDE (SYS_CATEGORY_CD);

/* Outbox & audit */
CREATE INDEX IX_TB_T_EMAIL_OUTBOX_PENDING ON dbo.TB_T_EMAIL_OUTBOX (CREATED_DT) WHERE STATUS = 'PENDING';
CREATE INDEX IX_TB_T_AUDIT_LOG_ENTITY ON dbo.TB_T_AUDIT_LOG (ENTITY, ENTITY_ID, CREATED_DT DESC);
CREATE INDEX IX_TB_T_AUDIT_LOG_USER   ON dbo.TB_T_AUDIT_LOG (USER_ID, CREATED_DT DESC);
GO

